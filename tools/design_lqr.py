"""Recompute the nominal ZOH / DARE gain and verify the checked-in C++ header."""

import argparse
from pathlib import Path

import numpy as np
from scipy.linalg import solve_discrete_are
from scipy.signal import cont2discrete

from model import linear_model


def design():
    a, b = linear_model()
    ad, bd, _, _, _ = cont2discrete((a, b, np.eye(4), np.zeros((4, 1))), 0.004, method="zoh")
    q = np.diag([80.0, 4.0, 200.0, 8.0])
    r = np.array([[0.4]])
    p = solve_discrete_are(ad, bd, q, r)
    gain = np.linalg.solve(r + bd.T @ p @ bd, bd.T @ p @ ad)
    poles = np.linalg.eigvals(ad - bd @ gain)
    controllability = np.column_stack([np.linalg.matrix_power(ad, i) @ bd for i in range(4)])
    if np.linalg.matrix_rank(controllability) != 4 or np.max(np.abs(poles)) >= 1:
        raise RuntimeError("nominal discrete model failed controllability or stability check")
    np.testing.assert_allclose(ad.T @ p @ (ad - bd @ gain) - p + q, 0, rtol=0, atol=1e-7)
    return gain.ravel(), poles


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="update the C++ gain header")
    args = parser.parse_args()
    gain, poles = design()
    header = Path(__file__).resolve().parents[1] / "controllers/balance/lqr_gain.hpp"
    values = ", ".join(f"{value:.8f}" for value in gain)
    contents = f"#pragma once\n\n#include <array>\n\n// Generated by tools/design_lqr.py.\ninline constexpr std::array<double, 4> kLqrGain = {{{values}}};\n"
    if args.write:
        header.write_text(contents, encoding="utf-8")
    elif header.read_text(encoding="utf-8") != contents:
        raise SystemExit("gain header differs; inspect the model or regenerate with --write")
    print("K =", values, "\nClosed-loop poles =", poles)
    print("Rank 4, DARE residual, stable poles and C++ gain header verified.")


if __name__ == "__main__":
    main()
